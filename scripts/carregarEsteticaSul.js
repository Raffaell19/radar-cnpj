async function executarCarga() {
  console.log(`Carregando ${CLINICAS_ESTETICA_SUL.length} clínicas de estética da Região Sul...`);

  // 1. Inserir no SQLite local
  const insertSqlite = db.prepare(`
    INSERT OR REPLACE INTO empresas (
      cnpj, razao_social, nome_fantasia, situacao_cadastral,
      cnae_codigo, cnae_descricao, capital_social, porte, natureza_juridica,
      uf, municipio, bairro, logradouro, numero, cep,
      ddd, telefone, eh_celular, email, eh_mei,
      data_abertura, socio_nome, socio_cargo, quadro_societario
    ) VALUES (
      ?, ?, ?, ?,
      ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?,
      ?, ?, ?, ?
    )
  `);

  for (const emp of CLINICAS_ESTETICA_SUL) {
    insertSqlite.run(
      emp.cnpj,
      emp.razao_social,
      emp.nome_fantasia,
      emp.situacao_cadastral,
      emp.cnae_codigo,
      emp.cnae_descricao,
      emp.capital_social,
      emp.porte,
      emp.natureza_juridica,
      emp.uf,
      emp.municipio,
      emp.bairro,
      emp.logradouro,
      emp.numero,
      emp.cep,
      emp.ddd,
      emp.telefone,
      emp.eh_celular,
      emp.email,
      emp.eh_mei,
      emp.data_abertura,
      emp.socio_nome,
      emp.socio_cargo,
      JSON.stringify(emp.quadro_societario)
    );
  }
  console.log('Gravado no SQLite com sucesso!');

  // 2. Inserir no Supabase remoto
  const supaRes = await salvarEmpresasSupabase(CLINICAS_ESTETICA_SUL);
  console.log('Gravado no Supabase com sucesso!', supaRes ? supaRes.length : 0);
}

executarCarga().catch(console.error);
